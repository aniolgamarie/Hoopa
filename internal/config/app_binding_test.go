func appBindingTestEntry() profile.Entry {
	return profile.Entry{Type: "mixed", Listen: "127.0.0.1", Port: 24680, Users: []profile.User{{Username: "app_user-1", Password: `private<&>\"-0123456789ABCDEFGHIJKLMN`}}}
}
func appBindingTestValue(t *testing.T) AppBinding {
	t.Helper()
	binding, e := NewAppBinding("app-A", strings.Repeat("a", 64), appBindingTestEntry())
	if e != nil {
		t.Fatal(e)
	}
	return binding
}
func appBindingTestBytes(t *testing.T, b AppBinding) []byte {
	t.Helper()
	raw, e := b.SensitiveBytes()
	if e != nil {
		t.Fatal(e)
	}
	return raw
}
func appBindingTestInvalid(t *testing.T, b AppBinding, e error) {
	t.Helper()
	if !errors.Is(e, ErrAppBinding) || !reflect.DeepEqual(b, AppBinding{}) {
		t.Fatal("invalid binding returned partial value", e)
	}
	for _, format := range []string{"%s", "%v", "%+v", "%#v"} {
		if got := fmt.Sprintf(format, e); got != "APP_BINDING_INVALID" {
			t.Fatal("error exposes private material", got)
		}
	}
}

func TestAppBindingCanonicalIndependentGoldenAndAlias(t *testing.T) {
	binding := appBindingTestValue(t)
	// Golden bytes/digest were independently generated by Python3 json+hashlib,
	// including Go's explicit HTML escaping. No writer under test computes want.
	const want = `{"schema_version":1,"app_id":"app-A","source_settings_sha256":"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa","entry":{"name":"app:4075576308e0a1a6e13034179f203731ff9f436d84c71723ff0efc587c5ab3a2","type":"mixed","listen":"127.0.0.1","port":24680,"udp":false,"users":[{"username":"app_user-1","password":"private\u003c\u0026\u003e\\\"-0123456789ABCDEFGHIJKLMN"}]}}`
	const digest = "1e99f16c2c37668b8591ff41178183e0595ecac6e9d075b4ff2472c3acca4515"
	const alias = "app:4075576308e0a1a6e13034179f203731ff9f436d84c71723ff0efc587c5ab3a2"
	if string(appBindingTestBytes(t, binding)) != want || binding.Digest() != digest {
		t.Fatal("canonical encoding/digest differs from independent v1 vector")
	}
	if AppEntryAlias("app-A") != alias || AppEntryAlias("app-a") != "app:f2524ca217411db466876bb97f8bc934e91fd8a11691a4bbde9b1fa49a65c9ed" {
		t.Fatal("alias does not hash exact case-sensitive ID bytes")
	}
	if binding.AppID() != "app-A" || binding.SettingsSHA256() != strings.Repeat("a", 64) {
		t.Fatal("safe identity getters")
	}
	entry, e := binding.SensitiveEntry()
	if e != nil || entry.Name != alias {
		t.Fatal("constructor did not fill alias")
	}
	decoded, e := DecodeAppBinding([]byte(want))
	if e != nil || decoded.Digest() != digest || !bytes.Equal(appBindingTestBytes(t, decoded), []byte(want)) {
		t.Fatal("exact writer round trip", e)
	}
	entry.Name = alias
	explicit, e := NewAppBinding("app-A", strings.Repeat("a", 64), entry)
	if e != nil || explicit.Digest() != digest {
		t.Fatal("explicit same alias changed encoding")
	}
	other, e := NewAppBinding("app-A", strings.Repeat("b", 64), entry)
	if e != nil || other.Digest() == digest {
		t.Fatal("parent settings identity unbound")
	}
	entry.Users[0].Password = strings.Repeat("z", 32)
	changed, e := NewAppBinding("app-A", strings.Repeat("a", 64), entry)
	if e != nil || changed.Digest() == digest {
		t.Fatal("credential omitted from commitment")
	}
}

func TestAppBindingRejectsInvalidIDHashAndEntry(t *testing.T) {
	for _, id := range []ID{"", "-app", "bad id", ID(strings.Repeat("a", 129)), ID(string([]byte{0xff}))} {
		t.Run("ID/"+fmt.Sprintf("%x", []byte(id)), func(t *testing.T) {
			b, e := NewAppBinding(id, strings.Repeat("a", 64), appBindingTestEntry())
			appBindingTestInvalid(t, b, e)
		})
	}
	for _, hash := range []string{"", strings.Repeat("a", 63), strings.Repeat("a", 65), strings.Repeat("A", 64), strings.Repeat("g", 64), strings.Repeat("a", 63) + " ", strings.Repeat("a", 63) + "\x00"} {
		t.Run("hash/"+fmt.Sprintf("%x", hash), func(t *testing.T) {
			b, e := NewAppBinding("app-A", hash, appBindingTestEntry())
			appBindingTestInvalid(t, b, e)
		})
	}
	cases := map[string]func(*profile.Entry){
		"wrong-name": func(e *profile.Entry) { e.Name = AppEntryAlias("other-app") }, "wrong-name-case": func(e *profile.Entry) { e.Name = strings.ToUpper(AppEntryAlias("app-A")) },
		"type-empty": func(e *profile.Entry) { e.Type = "" }, "other-type": func(e *profile.Entry) { e.Type = "http" },
		"dns-listen": func(e *profile.Entry) { e.Listen = "localhost" }, "wildcard": func(e *profile.Entry) { e.Listen = "0.0.0.0" }, "other-loopback": func(e *profile.Entry) { e.Listen = "127.0.0.2" }, "ipv6": func(e *profile.Entry) { e.Listen = "::1" }, "noncanonical-ip": func(e *profile.Entry) { e.Listen = "127.000.0.1" },
		"zero-port": func(e *profile.Entry) { e.Port = 0 }, "udp": func(e *profile.Entry) { e.UDP = true }, "nil-users": func(e *profile.Entry) { e.Users = nil }, "empty-users": func(e *profile.Entry) { e.Users = []profile.User{} }, "many-users": func(e *profile.Entry) { e.Users = append(e.Users, e.Users[0]) },
		"empty-user": func(e *profile.Entry) { e.Users[0].Username = "" }, "leading-punctuation": func(e *profile.Entry) { e.Users[0].Username = ".user" }, "colon-user": func(e *profile.Entry) { e.Users[0].Username = "user:name" }, "long-user": func(e *profile.Entry) { e.Users[0].Username = strings.Repeat("u", 129) }, "nonascii-user": func(e *profile.Entry) { e.Users[0].Username = "私有用户" },
		"short-password": func(e *profile.Entry) { e.Users[0].Password = strings.Repeat("p", 31) }, "long-password": func(e *profile.Entry) { e.Users[0].Password = strings.Repeat("p", 129) }, "password-colon": func(e *profile.Entry) { e.Users[0].Password = strings.Repeat("p", 31) + ":" }, "password-space": func(e *profile.Entry) { e.Users[0].Password = strings.Repeat("p", 31) + " " }, "password-control": func(e *profile.Entry) { e.Users[0].Password = strings.Repeat("p", 31) + "\n" }, "password-nonascii": func(e *profile.Entry) { e.Users[0].Password = strings.Repeat("p", 31) + "é" },
	}
	for name, edit := range cases {
		t.Run(name, func(t *testing.T) {
			entry := appBindingTestEntry()
			edit(&entry)
			b, e := NewAppBinding("app-A", strings.Repeat("a", 64), entry)
			appBindingTestInvalid(t, b, e)
		})
	}
	for _, port := range []uint16{1, 65535} {
		entry := appBindingTestEntry()
		entry.Port = port
		if _, e := NewAppBinding("app-A", strings.Repeat("0", 64), entry); e != nil {
			t.Fatal("valid port/hash boundary", port, e)
		}
	}
	id := ID("A" + strings.Repeat("._:-", 31) + "z12")
	if len(id) != 128 {
		t.Fatal("fixture ID bound")
	}
	if _, e := NewAppBinding(id, strings.Repeat("f", 64), appBindingTestEntry()); e != nil {
		t.Fatal("maximum common ID should work", e)
	}
}

// Only the two credential grammars are compared to the complete profile oracle;
// endpoint/settings collisions are deliberately outside this codec boundary.
func appBindingProfileAccepts(t *testing.T, entry profile.Entry) bool {
	t.Helper()
	if entry.Name == "" {
		entry.Name = AppEntryAlias("app-A")
	}
	candidate := profile.Config{Mode: "rule", LogLevel: "silent", FindProcessMode: "off", Controller: "127.0.0.1:20101", Secret: "Oracle-Shared-Secret-Has-At-Least-32-Bytes!", Listeners: []profile.Entry{entry}, Proxies: []map[string]any{}, Groups: []profile.Group{}, Rules: []string{"MATCH,REJECT"}}
	raw, e := json.Marshal(candidate)
	if e != nil {
		t.Fatal(e)
	}
	_, e = profile.Validate(raw, "app-binding-grammar")
	return e == nil
}
func TestAppBindingExactASCIICredentialGrammar(t *testing.T) {
	for c := 0; c < 256; c++ {
		t.Run(fmt.Sprintf("byte-%02x", c), func(t *testing.T) {
			entry := appBindingTestEntry()
			entry.Users[0].Password = strings.Repeat("p", 31) + string([]byte{byte(c)})
			_, e := NewAppBinding("app-A", strings.Repeat("a", 64), entry)
			valid := c >= 33 && c <= 126 && c != ':'
			if (e == nil) != valid || appBindingProfileAccepts(t, entry) != valid {
				t.Fatal("password ASCII grammar mismatch", c, e)
			}
			entry = appBindingTestEntry()
			entry.Users[0].Username = "u" + string([]byte{byte(c)})
			_, e = NewAppBinding("app-A", strings.Repeat("a", 64), entry)
			valid = c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '.' || c == '_' || c == '-'
			if (e == nil) != valid || appBindingProfileAccepts(t, entry) != valid {
				t.Fatal("username continuation grammar mismatch", c, e)
			}
			entry.Users[0].Username = string([]byte{byte(c)}) + "u"
			_, e = NewAppBinding("app-A", strings.Repeat("a", 64), entry)
			valid = c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9'
			if (e == nil) != valid || appBindingProfileAccepts(t, entry) != valid {
				t.Fatal("username first-byte grammar mismatch", c, e)
			}
		})
	}
	for _, size := range []int{1, 128} {
		entry := appBindingTestEntry()
		entry.Users[0].Username = strings.Repeat("u", size)
		entry.Users[0].Password = strings.Repeat("p", 128)
		if _, e := NewAppBinding("app-A", strings.Repeat("a", 64), entry); e != nil {
			t.Fatal("valid credential length boundary", size, e)
		}
	}
}

