func TestAppBindingOwnershipZeroAndFormatting(t *testing.T) {
	entry := appBindingTestEntry()
	binding, e := NewAppBinding("app-A", strings.Repeat("a", 64), entry)
	if e != nil {
		t.Fatal(e)
	}
	copyValue := binding
	original := appBindingTestBytes(t, binding)
	digest := binding.Digest()
	entry.Users[0].Password = "caller-mutated"
	entry.Users = append(entry.Users, profile.User{})
	got, e := binding.SensitiveEntry()
	if e != nil {
		t.Fatal(e)
	}
	got.Users[0].Password = "getter-mutated"
	got.Users[0].Username = "changed"
	got.Name = "changed"
	raw := appBindingTestBytes(t, binding)
	for i := range raw {
		raw[i] = 'x'
	}
	decodedInput := bytes.Clone(original)
	decoded, e := DecodeAppBinding(decodedInput)
	if e != nil {
		t.Fatal(e)
	}
	for i := range decodedInput {
		decodedInput[i] = 'x'
	}
	for _, value := range []AppBinding{binding, copyValue, decoded} {
		if value.Digest() != digest || !bytes.Equal(appBindingTestBytes(t, value), original) {
			t.Fatal("mutable alias rewrote private binding")
		}
		sensitive, e := value.SensitiveEntry()
		if e != nil || sensitive.Users[0].Password != appBindingTestEntry().Users[0].Password {
			t.Fatal("entry alias changed authority")
		}
	}
	var zero AppBinding
	if zero.Digest() != "" || zero.AppID() != "" || zero.SettingsSHA256() != "" {
		t.Fatal("zero identity getters usable")
	}
	if raw, e := zero.SensitiveBytes(); raw != nil || !errors.Is(e, ErrAppBinding) {
		t.Fatal("zero sensitive bytes usable")
	}
	if entry, e := zero.SensitiveEntry(); !reflect.DeepEqual(entry, profile.Entry{}) || !errors.Is(e, ErrAppBinding) {
		t.Fatal("zero sensitive entry usable")
	}
	for _, value := range []any{binding, &binding, copyValue, &copyValue, zero, &zero} {
		for _, format := range []string{"%v", "%+v", "%#v", "%s", "%q"} {
			message := fmt.Sprintf(format, value)
			if strings.Contains(message, "private<&>") || strings.Contains(message, "app_user-1") || strings.Contains(message, "source_settings_sha256") || strings.Contains(message, "24680") {
				t.Fatal("standard formatting exposed private record", message)
			}
			if !strings.Contains(message, "private material") {
				t.Fatal("private formatting marker missing", message)
			}
		}
		encoded, e := json.Marshal(value)
		if e != nil || string(encoded) != "{}" {
			t.Fatal("default JSON exposed binding", e)
		}
	}
}

func TestAppBindingSelfShapeDoesNotClaimSettingsAuthority(t *testing.T) {
	// The codec cannot know a real controller/shared entry or another binding.
	// Distinct parent hashes and hypothetical shared collisions stay syntactically
	// valid here; the coordinator/compiler must establish actual relationships.
	entry := appBindingTestEntry()
	entry.Port = 20101
	entry.Users[0].Password = "Oracle-Shared-Secret-Has-At-Least-32-Bytes!"
	a, e := NewAppBinding("app-A", strings.Repeat("0", 64), entry)
	if e != nil {
		t.Fatal("codec invented settings/endpoint authority", e)
	}
	b, e := NewAppBinding("app-B", strings.Repeat("0", 64), entry)
	if e != nil || a.Digest() == b.Digest() {
		t.Fatal("codec invented cross-binding collision check or omitted ID", e)
	}
}
