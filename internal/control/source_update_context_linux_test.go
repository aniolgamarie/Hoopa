func updateContextEncodeInvalid(t *testing.T, v sourceUpdateContext) {
	t.Helper()
	raw, err := encodeSourceUpdateContext(v)
	if raw != nil || err != ErrSourceContext {
		t.Fatal("encode exposed partial data or wrong error")
	}
}
func updateContextDecodeInvalid(t *testing.T, raw []byte) {
	t.Helper()
	v, err := decodeSourceUpdateContext(raw)
	if err != ErrSourceContext || !reflect.DeepEqual(v, sourceUpdateContext{}) {
		t.Fatal("decode exposed partial data or wrong error")
	}
	if strings.Contains(fmt.Sprint(err), "private-material") {
		t.Fatal("error exposed input")
	}
}
func updateContextRoundTrip(t *testing.T, v sourceUpdateContext) []byte {
	t.Helper()
	raw, err := encodeSourceUpdateContext(v)
	if err != nil {
		t.Fatal(err)
	}
	got, err := decodeSourceUpdateContext(raw)
	if err != nil || !reflect.DeepEqual(got, v) {
		t.Fatal("roundtrip mismatch", err)
	}
	return raw
}
func TestSourceUpdateContextGoldenAndLegalShapes(t *testing.T) {
	v := updateContextFixture()
	raw := updateContextRoundTrip(t, v)
	if string(raw) != updateContextGolden {
		t.Fatal("versioned complete JSON changed")
	}
	// Independently generated by Python stdlib json compact encoding + hashlib.
	if hash(raw) != "5a57ac7216467863ccb88d5983d5952fea405335e763eba4ea041d117bd34f53" {
		t.Fatal("independent context digest changed")
	}
	v.Source.UpdateHours = nil
	v.NextDue = nil
	v.RegionRules = []subscription.RegionRule{}
	v.Sequence = (1 << 53) - 1
	updateContextRoundTrip(t, v)
	op := config.ID("legacy-operation")
	v.Base.OperationID = &op
	updateContextRoundTrip(t, v)
	generation := config.Generation("generation:old")
	v.Base.Generation = &generation
	v.Base.ManifestSHA256 = strings.Repeat("e", 64)
	v.Base.DesiredRuntime = "running"
	v.Source.Source = config.SubscriptionSource{Kind: "https", URLSecretRef: "/private/url-secret"}
	updateContextRoundTrip(t, v)
	v.Base.DesiredRuntime = "stopped"
	v.RegionRules = []subscription.RegionRule{{Prefix: "東京 ", Region: "日本"}}
	updateContextRoundTrip(t, v)
	// The same rule constraints as Parse allow bounded UTF8, not only ISO codes.
	v.RegionRules = make([]subscription.RegionRule, 64)
	for i := range v.RegionRules {
		v.RegionRules[i] = subscription.RegionRule{Prefix: strings.Repeat("p", 256), Region: strings.Repeat("R", 64)}
	}
	updateContextRoundTrip(t, v)
}
