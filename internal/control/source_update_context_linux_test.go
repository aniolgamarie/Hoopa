func TestSourceUpdateContextTimeArithmeticAndCanonicalTimes(t *testing.T) {
	for _, start := range []string{"", "0001-01-01T00:00:00Z", "2026-10-28T00:00:00+00:00", "2026-10-28T00:00:00.100Z", "2026-10-28T00:00:00.1234567890Z", "2026-02-29T00:00:00Z", "2026-10-28T00:00:60Z", "10000-01-01T00:00:00Z"} {
		v := updateContextFixture()
		v.StartedAt = start
		updateContextEncodeInvalid(t, v)
	}
	for _, next := range []string{"2026-10-28T02:00:00.123456788Z", "2026-10-28T02:00:00.123456789+00:00", "2026-10-28T01:00:00.123456789Z", "", "0001-01-01T00:00:00Z"} {
		v := updateContextFixture()
		v.NextDue = &next
		updateContextEncodeInvalid(t, v)
	}
	v := updateContextFixture()
	v.StartedAt = "2024-02-29T23:00:00Z"
	due := "2024-03-01T01:00:00Z"
	v.NextDue = &due
	updateContextRoundTrip(t, v)
	// Largest integral hour duration fits only when the resulting date does too.
	max := uint64(math.MaxInt64 / int64(time.Hour))
	v.Source.UpdateHours = &max
	start, _ := time.Parse(time.RFC3339Nano, v.StartedAt)
	due = start.Add(time.Duration(max) * time.Hour).UTC().Format(time.RFC3339Nano)
	v.NextDue = &due
	updateContextRoundTrip(t, v)
	v = updateContextFixture()
	v.StartedAt = "9999-12-31T23:00:00Z"
	v.Source.UpdateHours = &max
	updateContextEncodeInvalid(t, v)
	v = updateContextFixture()
	v.StartedAt = "9999-12-31T23:00:00Z"
	one := uint64(1)
	v.Source.UpdateHours = &one
	updateContextEncodeInvalid(t, v)
}

